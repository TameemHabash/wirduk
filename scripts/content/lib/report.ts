import type { ChangeLogEntry, ContentModel } from './types.ts';

const SECTIONS: { kind: ChangeLogEntry['kind']; title: string }[] = [
  { kind: 'split', title: 'Category splits' },
  { kind: 'exclude', title: 'Adhkar left out of a split category' },
  { kind: 'remove-notes', title: 'Notes removed from a split category' },
  { kind: 'count', title: 'Count fixes' },
  { kind: 'title', title: 'Title fixes' },
  { kind: 'text', title: 'Text fixes' },
  { kind: 'wording', title: 'Wording from Dorar (owner approved)' },
  { kind: 'added', title: 'Adhkar added by the owner (not in the book)' },
  { kind: 'quote-marks', title: 'Quote marks (( )) removed' },
  { kind: 'line-breaks', title: 'Line breaks between the parts of a dhikr' },
  { kind: 'audio-repeats', title: 'Recordings that say the dhikr more than once' },
  { kind: 'cleanup', title: 'Character cleanup (no wording change)' },
];

const escapeCell = (s: string) => s.replace(/\|/g, '\\|').replace(/\r?\n/g, ' ');

/** Renders docs/content-changes.md. Generated: do not edit by hand. */
export function renderChangesReport(
  model: ContentModel,
  version: number,
  sourceCommit: string,
): string {
  const lines: string[] = [
    '# Content changes',
    '',
    '<!-- Generated by `npm run content:build`. Do not edit by hand. -->',
    '',
    'Every difference between the source (`rn0x/Adhkar-json`) and the shipped content database.',
    'Rules are in [decisions.md](decisions.md); the changes themselves are in `content-source/overrides.json`.',
    '',
    `- Content version: **${version}**`,
    `- Source commit: \`${sourceCommit}\``,
    `- Categories: **${model.categories.length}**, adhkar: **${model.adhkar.length}**, audio files used: **${model.audioFiles.length}**`,
    '',
  ];

  for (const { kind, title } of SECTIONS) {
    const entries = model.changes.filter((c) => c.kind === kind);
    lines.push(`## ${title} (${entries.length})`, '');
    if (entries.length === 0) {
      lines.push('None.', '');
      continue;
    }
    lines.push('| Where | Change |', '|---|---|');
    for (const e of entries) lines.push(`| ${escapeCell(e.where)} | ${escapeCell(e.detail)} |`);
    lines.push('');
  }
  return lines.join('\n');
}
