/**
 * Writes e2e/.generated/strings.js for the Maestro flows: every UI string of the app
 * (common.json and the owner's labels) as a regular expression, so flows find text by
 * its key and never hold typed Arabic.
 *
 *   node scripts/dev/e2e-strings.ts
 *
 * In a flow: `- runScript: ../.generated/strings.js`, then `tapOn: ${output.s['home.start']}`
 * (a pattern), or `inputText: ${output.raw['home.morningBadge']}` (the plain text).
 * `{{name}}` placeholders become `.*`; plural keys also get a base key that matches any form.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { OWNER_TEXTS } from '../../src/features/adwamuha/owner-texts.ts';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const common = JSON.parse(
  readFileSync(join(root, 'src/i18n/locales/ar/common.json'), 'utf8'),
) as Record<string, unknown>;

const PLURAL = /_(zero|one|two|few|many|other)$/;

/** A string as a full-match regular expression (Maestro matches the whole text). */
function toPattern(text: string): string {
  return text
    .split(/\{\{[^}]+\}\}/)
    .map((part) => part.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'))
    .join('.*')
    .replace(/\n/g, '.*');
}

const out: Record<string, string> = {};
/** The plain text, for `inputText` (e.g. a search word taken from a label). */
const raw: Record<string, string> = {};
function walk(node: unknown, prefix: string): void {
  if (typeof node === 'string') {
    out[prefix] = toPattern(node);
    raw[prefix] = node;
    const base = prefix.replace(PLURAL, '');
    if (base !== prefix) {
      out[base] = out[base] ? `${out[base]}|${out[prefix]}` : out[prefix];
    }
    return;
  }
  if (node && typeof node === 'object') {
    for (const [key, value] of Object.entries(node)) {
      walk(value, prefix ? `${prefix}.${key}` : key);
    }
  }
}
walk(common, '');
walk(OWNER_TEXTS, 'owner');

const file = join(root, 'e2e/.generated/strings.js');
mkdirSync(dirname(file), { recursive: true });
writeFileSync(
  file,
  `// GENERATED by scripts/dev/e2e-strings.ts. Do not edit.\n` +
    `output.s = ${JSON.stringify(out, null, 1)};\n` +
    `output.raw = ${JSON.stringify(raw, null, 1)};\n`,
);
console.log(`e2e strings: ${Object.keys(out).length} keys → ${file}`);
